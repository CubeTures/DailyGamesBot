"""Generates games/schema.json, the JSON Schema for config.toml."""

import json
from typing import Any

from pydantic import TypeAdapter

from src.games.models import GameConfig
from src.settings import GAMES_DIR

SCHEMA_PATH = GAMES_DIR / "schema.json"


def _select_trigger_by_type(schema: dict[str, Any]) -> None:
    # Editors (taplo, tombi) ignore the OpenAPI-style discriminator, so an
    # invalid trigger only gets "not valid under any of the schemas listed in
    # the 'oneOf'". Picking the model by `type` with if/then gives errors that
    # name the actual problem.
    triggers = schema["properties"]["triggers"]
    mapping: dict[str, str] = triggers["items"]["discriminator"]["mapping"]
    triggers["items"] = {
        "type": "object",
        "required": ["type"],
        "properties": {"type": {"enum": list(mapping)}},
        "allOf": [
            {
                "if": {"properties": {"type": {"const": trigger_type}}},
                "then": {"$ref": ref},
            }
            for trigger_type, ref in mapping.items()
        ],
    }


def json_schema() -> dict[str, Any]:
    schema = TypeAdapter(GameConfig).json_schema()
    _select_trigger_by_type(schema)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "Generated by `python3 -m src.games`; do not edit.",
        **schema,
    }


def write_schema() -> bool:
    """Regenerate games/schema.json; return True if it changed."""
    text = json.dumps(json_schema(), indent=2) + "\n"
    if SCHEMA_PATH.exists() and SCHEMA_PATH.read_text() == text:
        return False
    SCHEMA_PATH.write_text(text)
    return True
